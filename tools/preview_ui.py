"""Rasterize the actual portable C renderer, not a separately drawn mockup.

Uses the DLL generated by pytest and Pillow (e.g. bundled workspace Python).
No hardware access. Artifacts remain under ignored build/.
"""
import ctypes as C
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]


class UI(C.Structure):
    _fields_ = [("changed_at", C.c_uint32), ("pressed_at", C.c_uint32),
                ("candidate", C.c_uint8), ("stable", C.c_uint8),
                ("selected", C.c_uint8), ("page", C.c_uint8),
                ("armed", C.c_bool), ("consumed", C.c_bool)]


def main():
    lib = C.CDLL(str(ROOT / "build/host/ctaphid.dll"))
    rect = C.CFUNCTYPE(C.c_int, C.c_void_p, *([C.c_uint16]*5))
    lib.key_ui_render.argtypes = [C.POINTER(UI), rect, C.c_void_p]
    out = ROOT / "build/ui-preview"
    out.mkdir(parents=True, exist_ok=True)
    grid = Image.new("RGB", (3*264, 2*344), "#101110")
    for page in range(6):
        image = Image.new("RGB", (240,320))
        draw = ImageDraw.Draw(image)

        @rect
        def callback(_, x,y,w,h,color):
            assert 0<=x<x+w<=240 and 0<=y<y+h<=320
            rgb = ((color>>11)*255//31, ((color>>5)&63)*255//63, (color&31)*255//31)
            draw.rectangle((x,y,x+w-1,y+h-1), fill=rgb)
            return 0

        assert lib.key_ui_render(C.byref(UI(page=page)),callback,None) == 0
        image.save(out / f"page-{page}.png")
        grid.paste(image, ((page%3)*264+12, (page//3)*344+12))
    grid.resize((1584,1376), Image.Resampling.NEAREST).save(out / "overview.png")
    print(out / "overview.png")


if __name__ == "__main__":
    main()
